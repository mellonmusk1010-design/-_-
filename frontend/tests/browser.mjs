import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
import { preview } from 'vite'

const server = await preview({ preview: { host: '127.0.0.1', port: 0 } })
let browser
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error))
  await page.goto(server.resolvedUrls.local[0])
  const click = name => page.getByRole('button', { name, exact: true }).click()
  const check = async (selector, expected) => assert.match(await page.locator(selector).innerText(), expected)
  const pick = name => page.getByRole('button', { name, exact: true }).press('Enter')
  await click('▷ 탐색 시작')
  await check('.route', /교실 PC.*1층 라우터.*학교 서버/)
  await check('.inspector', /전체 비용\s*6/)
  await check('.trace-content', /이전 정점/)
  await click('다음 단계')
  await check('.controls', /2 \/ 6/)
  await click('이전 단계')
  await check('.controls', /1 \/ 6/)
  await page.getByLabel('재생 속도').selectOption('4')
  await click('재생')
  await page.getByRole('button', { name: '일시정지', exact: true }).waitFor()
  await click('일시정지')
  await page.getByLabel('알고리즘').selectOption('0')
  await click('▷ 탐색 시작')
  await check('.trace-content', /BFS 큐/)
  await page.getByLabel('알고리즘').selectOption('1')
  await click('예제 장애 발생')
  await check('.route', /2층 라우터/)
  await check('.inspector', /전체 비용\s*10/)
  await check('.inspector', /66\.7%/)
  await click('작업 기록')
  await check('.events', /장애.*1층 라우터/)
  await click('↶ 장애 작업 되돌리기')
  await check('.route', /1층 라우터/)
  await page.getByLabel('시나리오').selectOption('1')
  await click('예제 장애 발생')
  await check('.route', /예비 중계기.*소방서/)
  await pick('주 중계기')
  await click('복구')
  await check('.route', /주 중계기/)
  await page.getByLabel('시나리오').selectOption('2')
  await click('예제 장애 발생')
  await check('.health', /통신 불가/)
  await check('.inspector', /도달 가능 장비\s*3\/6/)
  await click('초기화')
  await check('.health', /통신 가능/)
  await click('서버')
  await page.getByLabel('장비 이름').fill('검증 서버')
  const node = page.getByRole('button', { name: '검증 서버', exact: true })
  const before = await node.getAttribute('transform')
  const position = await node.locator('rect').first().boundingBox()
  await page.mouse.move(position.x + position.width / 2, position.y + position.height / 2)
  await page.mouse.down()
  await page.mouse.move(position.x + position.width / 2 + 35, position.y + position.height / 2 - 20, { steps: 4 })
  await page.mouse.up()
  assert.notEqual(await node.getAttribute('transform'), before)
  await click('확대')
  await check('.zoom', /125%/)
  await click('축소')
  await click('연결')
  await page.getByLabel('연결 비용').fill('3')
  await pick('학교 서버')
  await pick('검증 서버')
  await page.getByLabel('목적 장비').selectOption({ label: '검증 서버' })
  await check('.inspector', /전체 비용\s*9/)
  const line = '학교 서버 ↔ 검증 서버 회선'
  await pick(line)
  await page.getByLabel('회선 비용').fill('4')
  await click('비용 적용')
  await check('.inspector', /전체 비용\s*10/)
  await click('장애 발생')
  await check('.health', /통신 불가/)
  await click('복구')
  await check('.health', /통신 가능/)
  await click('삭제')
  await check('.health', /통신 불가/)
  await click('선택')
  await pick('검증 서버')
  await click('삭제')
  assert.equal(await node.count(), 0)
  await click('프로젝트 정보')
  await page.getByRole('dialog').waitFor()
  await click('닫기')
  assert.deepEqual(errors, [])
  console.log('NetRecover Chromium integration checks passed.')
} finally {
  await browser?.close()
  await new Promise(resolve => server.httpServer.close(resolve))
}
